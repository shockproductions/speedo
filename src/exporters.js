// Export formats: CSV channel log, GPX track, and RaceLogic VBO (read by Circuit Tools,
// RaceRender, Telemetry Overlay and most lap-analysis software).

function lapNumberAt(laps, t) {
  const lap = laps.find((item) => t >= item.start && t < item.end);
  return lap ? lap.number : 0;
}

const cell = (value, digits) => (Number.isFinite(value) ? value.toFixed(digits) : "");

export function runToCsv(run) {
  const analysis = run.analysis;
  const headers = [
    "time_s",
    "lap",
    "lat",
    "lon",
    "speed_kmh",
    "distance_m",
    "long_g",
    "lat_g",
    "yaw_rate_dps",
    "drift_angle_deg",
  ];
  const rows = analysis.series.map((row) =>
    [
      cell(row.t, 2),
      lapNumberAt(analysis.laps, row.t),
      cell(row.la, 7),
      cell(row.lo, 7),
      cell(row.v, 2),
      cell(row.d, 1),
      cell(row.lon, 3),
      cell(row.lat, 3),
      cell(row.yaw, 2),
      cell(row.beta, 1),
    ].join(","),
  );
  return [headers.join(","), ...rows].join("\n");
}

function originEpoch(run) {
  return Number.isFinite(run.startedAt) ? run.startedAt : new Date(run.date).getTime();
}

export function runToGpx(run) {
  const origin = originEpoch(run);
  const points = run.analysis.points
    .map(
      (point) =>
        `      <trkpt lat="${point.lat.toFixed(7)}" lon="${point.lon.toFixed(7)}"><time>${new Date(
          origin + point.t * 1000,
        ).toISOString()}</time><extensions><speed>${(point.v / 3.6).toFixed(2)}</speed></extensions></trkpt>`,
    )
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="Speedo" xmlns="http://www.topografix.com/GPX/1/1">
  <trk>
    <name>${new Date(run.date).toLocaleString()}</name>
    <trkseg>
${points}
    </trkseg>
  </trk>
</gpx>
`;
}

function vboTime(epochMs) {
  const date = new Date(epochMs);
  const hh = String(date.getUTCHours()).padStart(2, "0");
  const mm = String(date.getUTCMinutes()).padStart(2, "0");
  const ss = (date.getUTCSeconds() + date.getUTCMilliseconds() / 1000).toFixed(2).padStart(5, "0");
  return `${hh}${mm}${ss}`;
}

function signed(value, width, digits) {
  const text = Math.abs(value).toFixed(digits).padStart(width, "0");
  return `${value < 0 ? "-" : "+"}${text}`;
}

// VBO stores latitude and longitude in minutes, with longitude positive to the WEST.
export function runToVbo(run) {
  const origin = originEpoch(run);
  const created = new Date(run.date);
  const rows = run.analysis.series.map((row) =>
    [
      "008",
      vboTime(origin + row.t * 1000),
      signed(row.la * 60, 11, 5),
      signed(-row.lo * 60, 11, 5),
      row.v.toFixed(3).padStart(7, "0"),
      "000.00",
      "+00000.00",
      signed(row.lon ?? 0, 4, 2),
      signed(row.lat ?? 0, 4, 2),
    ].join(" "),
  );
  return `File created on ${created.toLocaleDateString("en-GB")} @ ${created.toLocaleTimeString("en-GB")}

[header]
satellites
time
latitude
longitude
velocity kmh
heading
height
longacc
latacc

[comments]
Generated by Speedo (10 Hz resampled)

[column names]
sats time lat long velocity heading height longacc latacc

[data]
${rows.join("\n")}
`;
}
